package compiler

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// TranspileDir recursively finds .gox files and transpiles them to .gox.go
func TranspileDir(dir string) error {
	return filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if !info.IsDir() && strings.HasSuffix(path, ".gox") {
			return TranspileFile(path)
		}
		return nil
	})
}

// TranspileFile transpiles a single .gox file into a .gox.go file
func TranspileFile(goxPath string) error {
	content, err := os.ReadFile(goxPath)
	if err != nil {
		return err
	}

	transpiled, err := Transpile(string(content))
	if err != nil {
		return fmt.Errorf("failed to transpile %s: %w", goxPath, err)
	}

	outPath := goxPath + ".go"
	// Optional: add a generated comment
	header := "// Code generated by GoKS GOX compiler. DO NOT EDIT.\n"
	
	return os.WriteFile(outPath, []byte(header+transpiled), 0644)
}

// Transpile converts a .gox string to valid Go component syntax.
func Transpile(content string) (string, error) {
	// Simple transpiler: 
	// We use regex to find `<Tag ...>...</Tag>`
	// This is a naive implementation that works for the generated templates.
	// For production, a proper AST-based or recursive descent parser is needed.
	
	// A naive approach: replace HTML tags sequentially from inside out
	// First, match self closing tags <tag attr="value" />
	// Then match <tag>content</tag>
	
	// Convert HTML comments to Go comments (optional)
	
	reSelfClosing := regexp.MustCompile(`(?s)<([a-zA-Z0-9]+)\s*([^>]*?)\s*/>`)
	reTag := regexp.MustCompile(`(?s)<([a-zA-Z0-9]+)\s*([^>]*?)>(.*?)</\1>`)
	
	// Keep parsing until no more tags are found
	for {
		matched := false
		
		content = reSelfClosing.ReplaceAllStringFunc(content, func(m string) string {
			matched = true
			parts := reSelfClosing.FindStringSubmatch(m)
			tag := parts[1]
			attrs := parts[2]
			return formatGoNode(tag, attrs, "")
		})
		
		content = reTag.ReplaceAllStringFunc(content, func(m string) string {
			matched = true
			parts := reTag.FindStringSubmatch(m)
			tag := parts[1]
			attrs := parts[2]
			inner := parts[3]
			return formatGoNode(tag, attrs, inner)
		})
		
		if !matched {
			break
		}
	}
	
	return content, nil
}

func formatGoNode(tag, attrs, inner string) string {
	goTag := strings.ToUpper(tag[0:1]) + tag[1:]
	
	innerProcessed := strings.TrimSpace(inner)
	
	// If inner has multiple comma separated parts, we keep them as args
	// e.g. html.Div(child1, child2)
	
	var children []string
	if innerProcessed != "" {
		// Split by comma if it looks like a list of components, otherwise check if it's text
		if strings.HasPrefix(innerProcessed, "{") && strings.HasSuffix(innerProcessed, "}") {
			innerExpr := innerProcessed[1 : len(innerProcessed)-1]
			children = append(children, fmt.Sprintf("component.C(%s)", innerExpr))
		} else if strings.HasPrefix(innerProcessed, "html.") || strings.HasPrefix(innerProcessed, "component.") {
			children = append(children, innerProcessed)
		} else {
			// Plain text
			children = append(children, fmt.Sprintf("%q", innerProcessed))
		}
	}
	
	args := strings.Join(children, ", ")
	res := fmt.Sprintf("html.%s(%s)", goTag, args)
	
	if class := extractAttr(attrs, "class"); class != "" {
		res += fmt.Sprintf(`.Class("%s")`, class)
	}
	if id := extractAttr(attrs, "id"); id != "" {
		res += fmt.Sprintf(`.ID("%s")`, id)
	}
	// For other attrs, we could do .Attr(k, v)
	
	return res
}

func extractAttr(attrs, name string) string {
	re := regexp.MustCompile(fmt.Sprintf(`%s="([^"]+)"`, name))
	m := re.FindStringSubmatch(attrs)
	if len(m) > 1 {
		return m[1]
	}
	return ""
}
